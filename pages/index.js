function calcHonmeisei(year, month, day) {
  const risshun = new Date(year, 1, 4);
  const birth = new Date(year, month - 1, day);
  let y = birth < risshun ? year - 1 : year;
  let s = String(y).split("").reduce((a, b) => a + Number(b), 0);
  while (s > 9) s = String(s).split("").reduce((a, b) => a + Number(b), 0);
  return ((11 - (s % 9)) % 9) || 9;
}

